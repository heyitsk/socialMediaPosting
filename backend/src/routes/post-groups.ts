const retryTarget = createRoute({
  method: "post",
  path: "/{groupId}/targets/{postId}/retry",
  tags: ["Posts"],
  summary: "Send one FAILED target again, now",
  request: { params: groupParamsSchema.extend({ postId: z.string() }) },
  responses: {
    200: {
      description: "The group after queueing the retry",
      content: { "application/json": { schema: postGroupSchema } },
    },
    404: { description: "Not found" },
    409: { description: "Target isn't FAILED" },
  },
});

async function findGroup(workspaceId: string, groupId: string) {
  const group = await prisma.postGroup.findFirst({
    where: { id: groupId, workspaceId },
    include: postGroupInclude,
  });
  if (!group) {
    throw new HTTPException(404, { message: "Post not found" });
  }
  return group;
}

type CreateBody = z.infer<typeof createPostGroupSchema>;
type TargetInput = CreateBody["targets"][number];

interface ResolvedTarget {
  input: TargetInput;
  account: ConnectedAccount & { platform: PostablePlatform };
  mediaType: MediaType;
  caption: string;
  media: TargetMedia;
}

// All-or-nothing (websitePlan.md §10.1 decision 3): every problem is collected
// so the composer can show them all and offer "deselect invalid targets".
async function validate(workspaceId: string, body: CreateBody) {
  const errors: string[] = [];
  const targetErrors = new Map<string, string[]>();
  const addTargetError = (connectedAccountId: string, message: string) => {
    targetErrors.set(connectedAccountId, [
      ...(targetErrors.get(connectedAccountId) ?? []),
      message,
    ]);
  };

  const scheduledFor = body.scheduledFor ? new Date(body.scheduledFor) : null;
  if (scheduledFor) {
    const lead = scheduledFor.getTime() - Date.now();
    if (lead < MIN_SCHEDULE_LEAD_MS)
      errors.push("Scheduled time must be at least a couple of minutes from now");
    if (lead > MAX_SCHEDULE_AHEAD_MS) errors.push("Posts can be scheduled at most 90 days ahead");
  }

  const { contentKind, mediaAssetIds } = body;
  if (contentKind === "TEXT" && mediaAssetIds.length > 0)
    errors.push("Text posts can't have media");
  if (
    (contentKind === "IMAGE" || contentKind === "VIDEO" || contentKind === "STORY") &&
    mediaAssetIds.length !== 1
  ) {
    errors.push(contentKind === "VIDEO" ? "Add one video" : "Add one image");
  }
  if (contentKind === "CAROUSEL" && mediaAssetIds.length < 2)
    errors.push("A carousel needs at least 2 images");
  if (new Set(mediaAssetIds).size !== mediaAssetIds.length)
    errors.push("The same file is added twice");

  const found = await prisma.mediaAsset.findMany({
    where: { workspaceId, id: { in: mediaAssetIds }, status: "READY", groupId: null },
  });
  const assetsById = new Map(found.map((asset) => [asset.id, asset]));
  const media = mediaAssetIds
    .map((id) => assetsById.get(id))
    .filter((asset): asset is MediaAsset => asset !== undefined);
  if (media.length !== mediaAssetIds.length) {
    errors.push("Some files haven't finished uploading or were removed — upload them again");
  }
  const wantVideo = contentKind === "VIDEO";
  for (const asset of media) {
    if (isVideoType(asset.contentType) !== wantVideo) {
      errors.push(
        `${asset.originalFilename} is ${wantVideo ? "an image" : "a video"} — this post needs ${wantVideo ? "a video" : "images"}`,
      );
    }
  }

  // The same account twice in one request is posted to once.
  const inputs = [
    ...new Map(body.targets.map((target) => [target.connectedAccountId, target])).values(),
  ];
  const accounts = await prisma.connectedAccount.findMany({
    where: { workspaceId, id: { in: inputs.map((target) => target.connectedAccountId) } },
  });
  const accountsById = new Map(accounts.map((account) => [account.id, account]));

  const resolved: ResolvedTarget[] = [];
  // Facebook-Page and Instagram-Login connections of one Instagram account
  // share platformAccountId — post to it once, silently (decision 6).
  const seenInstagram = new Set<string>();

  for (const input of inputs) {
    const id = input.connectedAccountId;
    const account = accountsById.get(id);
    if (!account) {
      addTargetError(id, "Account not found");
      continue;
    }
    if (account.disconnectedAt) {
      addTargetError(id, "Account is disconnected");
      continue;
    }
    if (!isPostablePlatform(account.platform)) {
      addTargetError(id, `${account.platform} accounts can't be posted to yet`);
      continue;
    }
    const platform = account.platform;

    if (platform === "INSTAGRAM") {
      if (seenInstagram.has(account.platformAccountId)) continue;
      seenInstagram.add(account.platformAccountId);
    }

    const blocked = reconnectReason(account, scheduledFor ?? new Date());
    if (blocked) addTargetError(id, blocked);

    const options = mediaTypesFor(platform, contentKind);
    if (options.length === 0) {
      addTargetError(id, `${platform} doesn't support ${contentKind.toLowerCase()} posts`);
      continue;
    }
    if (input.mediaType && !options.includes(input.mediaType)) {
      addTargetError(
        id,
        `${input.mediaType} isn't an option for ${contentKind.toLowerCase()} posts on ${platform}`,
      );
      continue;
    }
    // options is non-empty here (checked above).
    const mediaType = input.mediaType ?? (options[0] as MediaType);

    const caption = (input.captionOverride ?? body.caption).trim();
    if (caption === "") addTargetError(id, "Caption is empty");
    if (captionLength(caption) > CAPTION_LIMITS[platform]) {
      addTargetError(
        id,
        `Caption is ${captionLength(caption)} characters — ${platform} allows ${CAPTION_LIMITS[platform]}`,
      );
    }
    if (platform === "INSTAGRAM" && countHashtags(caption) > INSTAGRAM_MAX_HASHTAGS) {
      addTargetError(id, `Instagram allows at most ${INSTAGRAM_MAX_HASHTAGS} hashtags`);
    }

    if (contentKind === "CAROUSEL") {
      const { min, max } = CAROUSEL_LIMITS[platform];
      if (mediaAssetIds.length < min || mediaAssetIds.length > max) {
        addTargetError(id, `${platform} carousels take ${min}-${max} images`);
      }
    }
    // Crops, pads, Instagram's JPEG conversion, and shapes the API refuses.
    const targetMedia = resolveTargetMedia(platform, mediaType, media, input.mediaFits);
    for (const error of targetMedia.errors) addTargetError(id, error);
    if (platform === "YOUTUBE" && !input.youtubeOptions)
      addTargetError(id, "YouTube needs a video title");

    resolved.push({
      input,
      account: account as ResolvedTarget["account"],
      mediaType,
      caption,
      media: targetMedia,
    });
  }

  // Uses the dimensions stored at upload. Only videos uploaded before those
  // were stored need a network probe — last, and only on otherwise-valid input.
  const shorts = resolved.filter((target) => target.mediaType === "SHORTS");
  const [video] = media;
  if (errors.length === 0 && shorts.length > 0 && video) {
    try {
      const shape =
        video.width && video.height && video.durationSeconds != null
          ? { width: video.width, height: video.height, durationSeconds: video.durationSeconds }
          : await probeMediaAsset(video);
      if (shape.durationSeconds == null) throw new Error("Couldn't read the video's duration");
      for (const target of shorts) {
        const problems: string[] = [];
        // A landscape video cropped or padded to 9:16 for this target is fine.
        const ratio = target.media.ratios.get(video.id) ?? shape.width / shape.height;
        if (!ratioWithin(ratio, { min: 0, max: 1 })) {
          problems.push(
            `it's landscape (${shape.width}x${shape.height}) — Shorts must be vertical or square. Crop or pad it for YouTube`,
          );
        }
        if (shape.durationSeconds > SHORTS_MAX_DURATION_SECONDS) {
          problems.push(
            `it's ${Math.round(shape.durationSeconds)}s long — Shorts can be at most ${SHORTS_MAX_DURATION_SECONDS}s`,
          );
        }
        for (const problem of problems)
          addTargetError(target.account.id, `Can't post as a Short: ${problem}`);
      }
    } catch (err) {
      for (const target of shorts) {
        addTargetError(
          target.account.id,
          err instanceof Error ? err.message : "Couldn't check the video's dimensions",
        );
      }
    }
  }

  return {
    errors,
    targetErrors: [...targetErrors].map(([connectedAccountId, messages]) => ({
      connectedAccountId,
      errors: messages,
    })),
    resolved,
    media,
    scheduledFor,
  };
}

// Another post claimed one of the files between validation and create.
class MediaTakenError extends Error {}

export const postGroupsRoute = new OpenAPIHono<WorkspaceEnv>()
  .openapi(createPostGroup, async (c) => {
    const body = c.req.valid("json");
    const { workspaceId, userId } = c.var;

    const existing = await prisma.postGroup.findUnique({
      where: { workspaceId_idempotencyKey: { workspaceId, idempotencyKey: body.idempotencyKey } },
      include: postGroupInclude,
    });
    if (existing) return c.json(serializePostGroup(existing), 200);

    const { errors, targetErrors, resolved, media, scheduledFor } = await validate(
      workspaceId,
      body,
    );
    if (errors.length > 0 || targetErrors.length > 0) {
      return c.json(
        { message: "Some of this post can't be sent", errors, targets: targetErrors },
        400,
      );
    }

    let group: Prisma.PostGroupGetPayload<{ include: typeof postGroupInclude }>;
    // Renditions to render once the transaction has committed.
    let toRender: string[] = [];
    try {
      group = await prisma.$transaction(async (tx) => {
        toRender = [];
        const created = await tx.postGroup.create({
          data: {
            workspaceId,
            createdByUserId: userId,
            contentKind: body.contentKind,
            caption: body.caption,
            // Uploaded media is linked below and signed at send time.
            mediaUrls: [],
            scheduledFor,
            idempotencyKey: body.idempotencyKey,
            status: scheduledFor ? "SCHEDULED" : "PROCESSING",
            posts: {
              create: resolved.map((target) => ({
                workspaceId,
                createdByUserId: userId,
                connectedAccountId: target.account.id,
                caption: target.caption,
                mediaType: target.mediaType,
                mediaUrls: [],
                platformOptions:
                  target.account.platform === "YOUTUBE" ? target.input.youtubeOptions : undefined,
                status: scheduledFor ? "SCHEDULED" : "PROCESSING",
              })),
            },
          },
          include: postGroupInclude,
        });
        const expiresAt = mediaExpiry(scheduledFor);
        for (const [position, asset] of media.entries()) {
          const { count } = await tx.mediaAsset.updateMany({
            where: { id: asset.id, groupId: null, status: "READY" },
            data: { groupId: created.id, position, expiresAt },
          });
          if (count !== 1) throw new MediaTakenError();
        }

        // Targets asking for the same crop of a file share one rendition.
        const postIdByAccount = new Map(
          created.posts.map((post) => [post.connectedAccountId, post.id]),
        );
        for (const target of resolved) {
          const postId = postIdByAccount.get(target.account.id);
          if (!postId) continue;
          for (const { asset, spec } of target.media.renditions) {
            const rendition = await tx.mediaRendition.upsert({
              where: {
                mediaAssetId_specHash: { mediaAssetId: asset.id, specHash: spec.specHash },
              },
              create: {
                mediaAssetId: asset.id,
                specHash: spec.specHash,
                mode: spec.mode,
                cropX: spec.crop?.x,
                cropY: spec.crop?.y,
                cropW: spec.crop?.w,
                cropH: spec.crop?.h,
                width: spec.width,
                height: spec.height,
                contentType: spec.contentType,
                key: renditionKey(asset.key, spec.specHash, spec.contentType),
              },
              update: {},
              select: { id: true, status: true },
            });
            await tx.postMediaRendition.create({
              data: { postId, mediaAssetId: asset.id, renditionId: rendition.id },
            });
            if (rendition.status === "PENDING" && !toRender.includes(rendition.id))
              toRender.push(rendition.id);
          }
        }
        return created;
      });
    } catch (err) {
      if (err instanceof MediaTakenError) {
        return c.json(
          {
            message: "Some of this post can't be sent",
            errors: ["A file was used in another post meanwhile — upload it again"],
            targets: [],
          },
          400,
        );
      }
      // Two concurrent submits with the same key — the other one won.
      if (err instanceof Prisma.PrismaClientKnownRequestError && err.code === "P2002") {
        const winner = await prisma.postGroup.findUniqueOrThrow({
          where: {
            workspaceId_idempotencyKey: { workspaceId, idempotencyKey: body.idempotencyKey },
          },
          include: postGroupInclude,
        });
        return c.json(serializePostGroup(winner), 200);
      }
      throw err;
    }

    // Rendered now, not at send time, so scheduled posts are ready early and
    // a failure shows up while the user is still here. A lost enqueue is
    // picked up by the render reconciler.
    for (const renditionId of toRender) {
      await enqueueRender(renditionId).catch((err: unknown) =>
        console.error(`couldn't queue render ${renditionId}:`, err),
      );
    }

    await Promise.all(
      group.posts.map(async (post) => {
        try {
          await enqueuePublish(post.id, post.attempt, scheduledFor);
        } catch (err) {
          console.error(`couldn't queue post ${post.id}:`, err);
          await markTargetFailed(
            post.id,
            post.connectedAccount.platform,
            "Couldn't queue this post — retry it",
            {
              attempt: post.attempt,
            },
          );
        }
      }),
    );

    return c.json(serializePostGroup(await findGroup(workspaceId, group.id)), 201);
  })
  .openapi(listPostGroups, async (c) => {
    const { limit } = c.req.valid("query");
    const groups = await prisma.postGroup.findMany({
      where: { workspaceId: c.var.workspaceId },
      include: postGroupInclude,
      orderBy: [{ createdAt: "desc" }, { id: "desc" }],
      take: limit,
    });
    return c.json(groups.map(serializePostGroup), 200);
  })
  .openapi(getPostGroup, async (c) => {
    const { groupId } = c.req.valid("param");
    return c.json(serializePostGroup(await findGroup(c.var.workspaceId, groupId)), 200);
  })
  .openapi(cancelPostGroup, async (c) => {
    const { groupId } = c.req.valid("param");
    const group = await findGroup(c.var.workspaceId, groupId);
    const pending = group.posts.filter((post) => post.status === "SCHEDULED");
    if (pending.length === 0) {
      throw new HTTPException(409, {
        message: "Nothing left to cancel — it has already been sent",
      });
    }

    // cancelledAt first: a publish job that's already running re-reads it and
    // stops, even if removing its queue entry below loses the race.
    await prisma.postGroup.update({ where: { id: groupId }, data: { cancelledAt: new Date() } });
    for (const post of pending) {
      await removePublishJob(post.id, post.attempt);
      await markTargetCancelled(post.id);
    }
    return c.json(serializePostGroup(await findGroup(c.var.workspaceId, groupId)), 200);
  })
  .openapi(retryTarget, async (c) => {
    const { groupId, postId } = c.req.valid("param");
    const group = await findGroup(c.var.workspaceId, groupId);
    const post = group.posts.find((target) => target.id === postId);
    if (!post) {
      throw new HTTPException(404, { message: "Post not found" });
    }

    const attempt = await prepareRetry(postId);
    if (attempt === "NOT_FAILED") {
      throw new HTTPException(409, { message: "Only failed posts can be retried" });
    }
    if (attempt === "LIMIT_REACHED") {
      throw new HTTPException(409, {
        message: `This post was already tried ${MAX_ATTEMPTS} times — create it again instead`,
      });
    }
    try {
      // A render that failed gets another go along with the post.
      for (const renditionId of await resetFailedRenditions(postId))
        await enqueueRender(renditionId);
      await enqueuePublish(postId, attempt);
    } catch (err) {
      console.error(`couldn't queue retry of post ${postId}:`, err);
      await markTargetFailed(
        postId,
        post.connectedAccount.platform,
        "Couldn't queue the retry — try again",
        { attempt },
      );
    }
    return c.json(serializePostGroup(await findGroup(c.var.workspaceId, groupId)), 200);
  });
